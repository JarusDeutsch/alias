const STORAGE_KEY = 'alias_locale'

function getStoredLocale(): Locale {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    if (v === 'ru' || v === 'uk' || v === 'en') return v
  } catch {
    // ignore
  }
  return 'ru'
}

let currentLocale: Locale = getStoredLocale()

// Синхронизируем lang при первой загрузке (setLocale при том же значении не вызывается)
if (typeof document !== 'undefined' && document.documentElement) {
  document.documentElement.lang = currentLocale === 'uk' ? 'uk' : currentLocale === 'en' ? 'en' : 'ru'
}

export function getLocale(): Locale {
  return currentLocale
}

/** Склонение «слово/слова/слов» по числу n для текущей локали */
export function pluralWords(n: number): string {
  const locale = currentLocale
  const mod10 = n % 10
  const mod100 = n % 100
  if (locale === 'ru') {
    if (mod10 === 1 && mod100 !== 11) return 'слово'
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'слова'
    return 'слов'
  }
  if (locale === 'uk') {
    if (mod10 === 1 && mod100 !== 11) return 'слово'
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'слова'
    return 'слів'
  }
  return n === 1 ? 'word' : 'words'
}

/** Склонение «очко/очка/очков» по числу n для карточки шеринга */
export function pluralPoints(n: number): string {
  const locale = currentLocale
  const mod10 = n % 10
  const mod100 = n % 100
  if (locale === 'ru') {
    if (mod10 === 1 && mod100 !== 11) return 'очко'
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'очка'
    return 'очков'
  }
  if (locale === 'uk') {
    if (mod10 === 1 && mod100 !== 11) return 'очко'
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'очка'
    return 'очок'
  }
  return n === 1 ? 'point' : 'points'
}

export function setLocale(locale: Locale) {
  if (currentLocale === locale) return
  currentLocale = locale
  try {
    localStorage.setItem(STORAGE_KEY, locale)
  } catch {
    // ignore
  }
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = locale === 'uk' ? 'uk' : locale === 'en' ? 'en' : 'ru'
  }
}

function interpolate(msg: string, params: Record<string, string | number>): string {
  return msg.replace(/\{\{(\w+)\}\}/g, (_fullMatch, paramKey) => String(params[paramKey] ?? ''))
}

export function t(key: string, params?: Record<string, string | number>): string {
  const msg = translations[currentLocale][key] ?? translations.ru[key] ?? key
  return params ? interpolate(msg, params) : msg
}
